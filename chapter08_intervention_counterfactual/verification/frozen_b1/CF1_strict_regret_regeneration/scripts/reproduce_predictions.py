#!/usr/bin/env python3
"""CF1 step 1: frozen artifact audit + per-row T0/T4/R4 prediction
reproduction.

Does not retrain anything. T0 is a direct passthrough of the already
-serialized per-row `mechanism_probability_H2` column. T4/R4 are
regenerated by re-invoking the exact same frozen fitting/window/candidate
choices already recorded in R3's own manifests (02_window_manifest.csv,
05_selected_candidate_by_outer_fold.csv), reusing g0/g0b's exposed
functions unchanged (the same reuse pattern g0b already uses on g0).
"""

from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve()
CF1 = HERE.parents[1]
B1 = HERE.parents[2]
R2 = B1 / "R2_mechanism_conditioned_risk_rescue"
R3 = B1 / "R3_temporal_mechanism_evidence"
R1 = B1 / "R1_age_conditioned_decision_recovery"
G0_DIR = R3 / "G0_temporal_consistency_and_convolution"
G0B_DIR = R3 / "G0B_risk_constrained_convolution"
DATA = R2 / "G1A_instrumented_replay_data"

sys.path[:0] = [str(R3 / "scripts")]
import run_g0_temporal_audit as g0  # noqa: E402
import run_g0b_risk_constrained_convolution as g0b  # noqa: E402

H1, H2 = g0.H1, g0.H2


def sha256_file(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def write_csv(path, rows, fields=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = fields or list(rows[0])
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def frozen_model_manifest():
    rows = []
    gate1_path = (
        R1 / "results/gate1_formal_age_necessity/"
        "gate1_frozen_receiver_models.json")
    rows.append({
        "method": "T0", "artifact_type": "serialized_json_model",
        "artifact_path": str(gate1_path.relative_to(B1)),
        "sha256": sha256_file(gate1_path),
        "source_commit": "c54b690 (Archive B1 R1 Gate 1 formal raw results)",
        "notes": "age_aware_model; predictions read directly from "
                 "decision_state_manifest.mechanism_probability_H2, "
                 "never refit",
    })
    for method, script_path, selection_csv in (
            ("T4", G0_DIR.parent / "scripts/run_g0_temporal_audit.py",
             G0_DIR / "02_window_manifest.csv"),
            ("R4", G0B_DIR.parent / "scripts/"
             "run_g0b_risk_constrained_convolution.py",
             G0B_DIR / "05_selected_candidate_by_outer_fold.csv")):
        rows.append({
            "method": method, "artifact_type": "deterministic_frozen_script"
                                                "+recorded_hyperparameters",
            "artifact_path": str(script_path.relative_to(B1)),
            "sha256": sha256_file(script_path),
            "source_commit": (
                "83d48de (Audit temporal mechanism consistency and "
                "convolution for B1)" if method == "T4" else
                "ca4d2b3 (Audit risk-constrained temporal convolution "
                "for B1)"),
            "notes": f"selection_csv={selection_csv.relative_to(B1)} "
                     f"sha256={sha256_file(selection_csv)}",
        })
    rows.append({
        "method": "ALL", "artifact_type": "input_data",
        "artifact_path": str(
            (DATA / "03_decision_state_manifest.csv").relative_to(B1)),
        "sha256": sha256_file(DATA / "03_decision_state_manifest.csv"),
        "source_commit": "4af64fd (Recover instrumented B1 Gate 1 "
                          "development replay data)",
        "notes": "1600 rows, delay in {1,2}, seeds 3000-3399",
    })
    return rows


def load_base_and_features():
    """Identical loader to g0.main() / g0b.load_data(), read-only."""
    states = pd.read_csv(DATA / "03_decision_state_manifest.csv")
    states = states[states.delay.isin([1, 2])].copy()
    assert states.seed.between(3000, 3399).all()
    manifest = pd.read_csv(DATA / "01_replay_manifest.csv")
    traces, trace_index = {}, {}
    for delay in (1, 2):
        row = manifest[
            (manifest.delay == delay) & (manifest.packet_loss == 0)].iloc[0]
        with np.load(R2 / row.trace_reference, allow_pickle=False) as z:
            traces[delay] = {
                "received": z["received"], "arrival": z["arrival_mask"]}
            trace_index[delay] = {str(r): i for i, r in enumerate(z["run_id"])}

    base, received, arrival = [], [], []
    for row in states.itertuples():
        idx = trace_index[row.delay][row.run_id]
        received.append(traces[row.delay]["received"][idx])
        arrival.append(traces[row.delay]["arrival"][idx])
        base.append({
            "run_id": row.run_id, "seed": int(row.seed),
            "mechanism": row.mechanism, "delay": int(row.delay),
            "outer_fold": int(row.outer_fold),
            "frozen_probability_h2": float(row.mechanism_probability_H2),
            "oracle_action": row.oracle_action,
            "potential_regret": float(row.potential_wrong_transfer_regret)})
    labels = np.asarray([b["mechanism"] == H2 for b in base], int)
    seeds = np.asarray([b["seed"] for b in base])
    static = np.asarray([
        g0.static_features(r, a, b["delay"])
        for r, a, b in zip(received, arrival, base)])
    return base, received, labels, seeds, static


def reproduce(base, received, labels, seeds, static):
    n = len(base)
    frozen_p = np.asarray([b["frozen_probability_h2"] for b in base])

    window_manifest = pd.read_csv(G0_DIR / "02_window_manifest.csv")
    t4_window = {
        int(r.outer_fold): int(r.selected_window)
        for r in window_manifest[window_manifest.method == "T4"].itertuples()}
    conv_by_length = {}
    for length in sorted(set(t4_window.values())):
        conv_by_length[length] = np.asarray([
            g0.convolution_features(g0.visible_series(r, length))
            for r in received])

    t4_pred = np.full(n, np.nan)
    for fold in range(5):
        train = np.asarray([r["outer_fold"] != fold for r in base])
        test = ~train
        length = t4_window[fold]
        x = np.column_stack([static, conv_by_length[length]])
        model = g0.fit_classifier(x[train], labels[train])
        t4_pred[test] = g0.probabilities(model, x[test])

    selection = pd.read_csv(G0B_DIR / "05_selected_candidate_by_outer_fold.csv")
    r4_pred = np.full(n, np.nan)
    for fold in range(5):
        train = np.asarray([r["outer_fold"] != fold for r in base])
        test = ~train
        length = t4_window[fold]
        x = np.column_stack([static, conv_by_length[length]])
        row = selection[
            (selection.outer_fold == fold)
            & (selection.method_family == "R4")].iloc[0]
        if bool(row.fallback_to_T0):
            r4_pred[test] = frozen_p[test]
        else:
            w, b = float(row.selected_w_H2), float(row.selected_b_H2)
            model = g0b.fit_classifier_costsensitive(x[train], labels[train], w)
            r4_pred[test] = g0b.probabilities_biased(model, x[test], b)

    return {"T0": frozen_p, "T4": t4_pred, "R4": r4_pred}


def verify_against_archive(base, predictions):
    archived = pd.read_csv(G0_DIR / "07_method_summary.csv").set_index("method")
    archived_g0b = pd.read_csv(G0B_DIR / "07_method_summary.csv").set_index("method")
    rows = []
    for method, source in (("T0", archived), ("T4", archived), ("R4", archived_g0b)):
        rows_out = g0.action_rows(base, predictions[method])
        m = g0.metrics(rows_out, method)
        arch = source.loc[method]
        for metric in ("balanced_accuracy", "coverage", "total_regret"):
            observed = m[metric]
            reference = float(arch[metric])
            rows.append({
                "method": method, "metric": metric,
                "archived_value": reference, "reproduced_value": observed,
                "abs_difference": abs(observed - reference),
                "reproduced_exactly": abs(observed - reference) < 1e-9,
            })
    return rows


def main():
    CF1.mkdir(parents=True, exist_ok=True)
    manifest_rows = frozen_model_manifest()
    write_csv(CF1 / "02_frozen_model_manifest.csv", manifest_rows)

    base, received, labels, seeds, static = load_base_and_features()
    predictions = reproduce(base, received, labels, seeds, static)
    verify_rows = verify_against_archive(base, predictions)
    write_csv(CF1 / "04_prediction_reproduction.csv", verify_rows)
    all_exact = all(r["reproduced_exactly"] for r in verify_rows)

    inventory_rows = []
    for method in ("T0", "T4", "R4"):
        inventory_rows.append({
            "method": method, "n_rows": len(base),
            "has_stored_per_row_predictions": method == "T0",
            "reconstruction_needed": method != "T0",
            "reconstruction_source":
                "decision_state_manifest.mechanism_probability_H2"
                if method == "T0" else
                "g0.fit_classifier + frozen 02_window_manifest.csv window"
                if method == "T4" else
                "g0b.fit_classifier_costsensitive/probabilities_biased + "
                "frozen 05_selected_candidate_by_outer_fold.csv",
        })
    write_csv(CF1 / "03_old_prediction_inventory.csv", inventory_rows)

    print(f"all_exact={all_exact}")
    for r in verify_rows:
        print(r)
    if not all_exact:
        raise SystemExit("CF1_PREDICTION_REPRODUCTION_FAILED")

    np.savez(
        CF1 / "_predictions_cache.npz",
        T0=predictions["T0"], T4=predictions["T4"], R4=predictions["R4"],
        run_id=np.asarray([b["run_id"] for b in base]),
        seed=seeds, labels=labels,
        outer_fold=np.asarray([b["outer_fold"] for b in base]),
        delay=np.asarray([b["delay"] for b in base]),
        mechanism=np.asarray([b["mechanism"] for b in base]),
        oracle_action_old=np.asarray([b["oracle_action"] for b in base]),
        potential_regret_old=np.asarray([b["potential_regret"] for b in base]),
    )
    return all_exact


if __name__ == "__main__":
    main()
